#!/usr/bin/env python3
"""Dump what the game's pixel shaders declare: constant buffers, textures and structured buffers.

Why this exists: guessing what a bound resource is from its size or format produced two wrong conclusions in this
project ("the first PS texture is the albedo", and a constant-buffer scan for a point-light array that found nothing).
The shader itself names its inputs, and the DXBC `RDEF` chunk carries those names, offsets, types and bind slots. It is
a declaration parse, not opcode scanning — the thing that was tried and abandoned on 2026-10-27 was reading instruction
tokens, which is a different problem.

Usage:
  dump_shader_decls.py <dir-with-ps_*.dxbc> [--md <out.md>] [--top N]

Read-only. Prints a summary: which names appear at which texture slots, which buffers are structured vs constant, and
the shaders that bind light buffers.
"""
import glob
import struct
import sys
from collections import Counter, defaultdict
from pathlib import Path

RESOURCE_TYPES = {0: 'cbuffer', 1: 'tbuffer', 2: 'texture', 3: 'sampler', 4: 'uav', 5: 'structured', 6: 'byteaddress'}


def chunks(data):
    if data[:4] != b'DXBC':
        return {}
    count = struct.unpack_from('<I', data, 28)[0]
    offsets = struct.unpack_from(f'<{count}I', data, 32)
    out = {}
    for offset in offsets:
        fourcc = data[offset:offset + 4].decode('ascii', 'replace')
        size = struct.unpack_from('<I', data, offset + 4)[0]
        out.setdefault(fourcc, []).append(data[offset + 8:offset + 8 + size])
    return out


def declarations(rdef):
    """(cbuffers, resources) from an RDEF chunk. cbuffer = (name, size, [(var, offset, size)])."""
    try:
        cb_count, cb_offset, res_count, res_offset = struct.unpack_from('<4I', rdef, 0)
    except struct.error:
        return [], []
    cbuffers, resources = [], []
    for i in range(cb_count):
        try:
            name_offset, var_count, var_offset, size = struct.unpack_from('<4I', rdef, cb_offset + 24 * i)
            name = rdef[name_offset:rdef.index(b'\0', name_offset)].decode('ascii', 'replace')
        except (struct.error, ValueError):
            continue
        variables = []
        for v in range(var_count):
            try:
                var_name_offset, start, var_size = struct.unpack_from('<3I', rdef, cb_offset + var_offset + 24 * v)
                var_name = rdef[var_name_offset:rdef.index(b'\0', var_name_offset)].decode('ascii', 'replace')
            except (struct.error, ValueError):
                break
            variables.append((var_name, start, var_size))
        cbuffers.append((name, size, variables))
    for i in range(res_count):
        try:
            name_offset, kind, _ret, _dim, _samples, bind_point, bind_count = struct.unpack_from(
                '<7I', rdef, res_offset + 32 * i)
            name = rdef[name_offset:rdef.index(b'\0', name_offset)].decode('ascii', 'replace')
        except (struct.error, ValueError):
            continue
        resources.append((name, RESOURCE_TYPES.get(kind, str(kind)), bind_point, bind_count))
    return cbuffers, resources


def main():
    args = [a for a in sys.argv[1:]]
    if not args:
        sys.exit(__doc__)
    directory = args[0]
    md_out = None
    if '--md' in args:
        md_out = Path(args[args.index('--md') + 1])
    top = int(args[args.index('--top') + 1]) if '--top' in args else 20

    files = sorted(glob.glob(str(Path(directory) / 'ps_*.dxbc')))
    if not files:
        sys.exit(f'no ps_*.dxbc under {directory}')

    textures = Counter()             # 'slot:name'
    cbuffers = Counter()
    cbuffer_slots = defaultdict(Counter)
    buffers = Counter()              # structured / tbuffer: 'slot:name:kind'
    light_shaders = []
    parsed = 0
    for path in files:
        chunk = chunks(Path(path).read_bytes())
        if 'RDEF' not in chunk:
            continue
        parsed += 1
        cbs, resources = declarations(chunk['RDEF'][0])
        for name, _size, _vars in cbs:
            cbuffers[name] += 1
        for name, kind, bind_point, _count in resources:
            if kind == 'cbuffer':
                cbuffer_slots[name][bind_point] += 1
            if kind == 'texture':
                textures[f'{bind_point}:{name}'] += 1
            elif kind in ('structured', 'tbuffer', 'byteaddress'):
                buffers[f'{bind_point}:{name}:{kind}'] += 1
        if any('Light' in name and kind in ('structured', 'tbuffer') for name, kind, _b, _c in resources):
            light_shaders.append((Path(path).name, [(n, k, b) for n, k, b, _c in resources
                                                    if 'Light' in n or 'Tile' in n]))

    lines = ['# What the game\'s pixel shaders declare',
             '',
             f'Generated by `analysis/checks/dump_shader_decls.py` from {parsed} shader blobs in '
             f'`{directory}`. These are declaration names from each shader\'s DXBC `RDEF` chunk, i.e. the game\'s own '
             'naming of every input, not an inference from sizes or formats.',
             '',
             '## Textures, by bind slot', '',
             '| slot | names in that slot (shader count) |', '| --- | --- |']
    slot_names = defaultdict(list)
    for key, count in textures.items():
        slot, name = key.split(':', 1)
        slot_names[int(slot)].append((count, name))
    for slot in sorted(slot_names):
        named = ', '.join(f'`{n}` ({c})' for c, n in sorted(slot_names[slot], reverse=True)[:4])
        lines.append(f'| {slot} | {named} |')

    lines += ['', '## Structured and table buffers (the shape of the renderer)', '',
              '| slot | buffer | kind | shaders |', '| --- | --- | --- | --- |']
    for key, count in sorted(buffers.items(), key=lambda kv: -kv[1])[:top]:
        slot, name, kind = key.split(':')
        lines.append(f'| {slot} | `{name}` | {kind} | {count} |')

    lines += ['', '## Light buffers', '',
              'A point-light array and a per-tile index buffer mean the renderer culls lights per screen tile and reads '
              'them from structured buffers, not from a constant buffer. That is why scanning captured constant-buffer '
              'payloads for a light array found nothing usable.', '',
              '| shader | light buffers (name, kind, bind slot) |', '| --- | --- |']
    for name, entries in light_shaders[:10]:
        lines.append(f'| `{name}` | ' + ', '.join(f'`{n}` ({k}, {b})' for n, k, b in entries) + ' |')

    lines += ['', '## Constant buffers, with their bind slot', '',
              'A shader\'s cbuffer is bound at a fixed slot, so this is what a proxy has to read to get the value: for '
              'the scene shaders, slot 12 is `HPixel_Buffer`, 13 `CamParam_HPixel_Buffer`, 3 `MeshBuffer1`, '
              '2 `PSParamBuffer1`, 0 `SceneBuffer`, 4 `ModelBuffer`, 8 `InsatncingParamBuffer`.', '',
              '| shader count | cbuffer | typical bind slot |', '| --- | --- | --- |']
    for name, count in cbuffers.most_common(top):
        slots = sorted(cbuffer_slots[name].items(), key=lambda kv: -kv[1])
        where = ', '.join(f'{slot} ({n})' for slot, n in slots[:3])
        lines.append(f'| {count} | `{name}` | {where} |')

    text = '\n'.join(lines) + '\n'
    if md_out:
        md_out.write_text(text)
        print(f'wrote {md_out} ({len(lines)} lines) from {parsed} shaders')
    else:
        print(text)


if __name__ == '__main__':
    main()
