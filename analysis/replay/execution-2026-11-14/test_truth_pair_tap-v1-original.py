def unsigned_float(bits, mantissa):
    exponent, fraction = bits >> mantissa, bits & ((1 << mantissa) - 1)
    if exponent == 31:
        return math.inf if fraction == 0 else math.nan
    if exponent == 0:
        return math.ldexp(fraction, -14 - mantissa)
    return math.ldexp(1 + fraction / (1 << mantissa), exponent - 15)


def pixel(raw, x, y):
    width, height, fmt = struct.unpack_from('<3I', raw)
    assert len(raw) == 12 + width * height * 4, 'raw payload includes pitch padding or is truncated'
    assert 0 <= x < width and 0 <= y < height
    at = 12 + 4 * (y * width + x)
    if fmt == 26:
        word, = struct.unpack_from('<I', raw, at)
        return (unsigned_float(word & 2047, 6), unsigned_float((word >> 11) & 2047, 6), unsigned_float(word >> 22, 5))
    rgb = tuple(raw[at:at+3])
    assert fmt in (28, 87, 91), ('unsupported raw format', fmt)
    return tuple(v / 255 for v in (rgb[::-1] if fmt in (87, 91) else rgb))


def check():
    # Hand-computed format checks, not generated by the candidate.
    assert unsigned_float(0, 6) == 0 and unsigned_float(1, 6) == 2**-20
    assert unsigned_float(15 << 6, 6) == 1 and unsigned_float(16 << 5, 5) == 2
    assert math.isinf(unsigned_float(31 << 6, 6)) and math.isnan(unsigned_float((31 << 6) | 1, 6))
    work = Path(os.environ['T1_GATE_SESSION']) / 'work'
    work.mkdir()
    fixture = A / 'runtime/hud-evidence/ps_1888250464.dxbc'
    assert fixture.is_file(), 'required native HUD bytecode fixture unavailable; gate not exercised'
    tmo.build(work)
    gpp = ['x86_64-w64-mingw32-g++', '-std=c++17', '-O2', '-Wall', '-Wextra', '-Werror', '-shared',
           '-static', '-static-libgcc', '-static-libstdc++', '-isystem', str(A / 'remix-probe/vendor')]
    r = subprocess.run([*gpp, str(C / 'remix_live_fake_runtime.cpp'), '-ld3d9', '-o', str(work / 'fake.dll')], capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-1600:]
    scene = work / 'scene'
    (scene / 'scene_textures').mkdir(parents=True)
    (scene / 'scene.bin').write_bytes(ts.scene_bytes(ts.CAMERA, ts.DRAWS, ts.TEXTURES, ts.TRIS))
    def win(p):
        return 'Z:' + str(p).replace('/', '\\')
    base = {'NIER_REMIX': '1', 'NIER_REMIX_LIVE': '1', 'NIER_REMIX_RUNTIME': win(work / 'fake.dll'),
            'NIER_REMIX_SCENE': win(scene / 'scene.bin'), 'MOCK_FRAME_MS': '40',
            'MOCK_CAMERA': 'live-native-hud', 'MOCK_NATIVE_HUD_PS': win(fixture)}
    def scenario(name, extra):
        saved = os.environ.copy()
        try:
            for key in list(os.environ):
                if key.startswith(('NIER_', 'MOCK_', 'FAKE_')) and key != 'NIER_RUN_TOKEN': os.environ.pop(key)
            tex = work / (name + '-textures'); tex.mkdir()
            os.environ.update(base | {'NIER_REMIX_LIVE_TEX': win(tex)} | extra)
            d, result, log = tmo.scenario(work, name, b'[Rendering]\r\nPreset=Custom75\r\n', True, (0, 0))
        finally:
            os.environ.clear(); os.environ.update(saved)
        assert result.get('presented') == '80', result
        assert result.get('hud_state_lost') == '0' and result.get('cs_lost') == '0', result
        assert 'native HUD handoff' in log, 'fixture never exercised native handoff'
        raw = (d / 'capture-after.raw').read_bytes()
        assert all(abs(a-b) < .10 for a, b in zip(pixel(raw, 1900, 8), (v/255 for v in tr.REMIX))), 'handoff output changed'
        return d, log, raw
    off_dir = work / 'off-pairs'
    off, log, raw_off = scenario('off', {})
    assert not off_dir.exists() and 'remix: truth-pair' not in log.lower(), 'default tap produced files/logs'
    on_dir = work / 'on-pairs'; on_dir.mkdir()
    on, log, raw_on = scenario('on', {'NIER_REMIX_LIVE_TRUTH_PAIR_DIR': win(on_dir)})
    assert raw_on == raw_off, 'tap changed displayed bytes (default compatibility broken)'
    records = sorted(on_dir.glob('*.json'))
    assert 1 <= len(records) <= 4, 'opt-in tap missing or unbounded (max4 attempts/session)'
    matched = 0
    for f in records:
        m = json.loads(f.read_text())
        assert m['version'] == 1 and m['tap_stage'] == 'before-native-hud-overwrite'
        assert m['calibrated'] is False, 'pre-final float tap claimed calibrated truth'
        assert all(isinstance(m[k], int) and m[k] > 0 for k in ['game_frame_id', 'remix_frame_id', 'remix_source_id',
                                                              'game_camera_sequence', 'remix_camera_sequence', 'capture_us', 'remix_completed_us'])
        assert m['capture_us'] >= m['remix_completed_us'], 'timestamp domains/order invalid'
        assert len(m['game_camera']) == len(m['remix_camera']) == 14
        camera_match = all(math.isfinite(a) and math.isfinite(b) and abs(a-b) <= 1e-4 for a,b in zip(m['game_camera'],m['remix_camera']))
        assert m['camera_matched'] == camera_match, 'camera alignment claim contradicts recorded parameters'
        assert 'R11G11B10_FLOAT' in m['game_encoding'] and 'unknown' in m['game_encoding'].lower()
        assert isinstance(m['remix_encoding'], str) and m['remix_encoding']
        if not camera_match:
            assert m['status'] == 'rejected-camera' and not m.get('game_file') and not m.get('remix_file')
            continue
        assert m['status'] == 'candidate', m
        matched += 1
        for key in ['game_file', 'remix_file']:
            assert Path(m[key]).name == m[key] and not any(c in m[key] for c in '/\\:'), 'raw file not relative to pair root'
        game = (on_dir / m['game_file']).read_bytes(); remix = (on_dir / m['remix_file']).read_bytes()
        assert struct.unpack_from('<3I', game) == (1920, 1080, 26)
        assert struct.unpack_from('<2I', remix) == (1920, 1080)
        for point in [(1900, 8), (960, 540), (96, 540)]:
            assert all(abs(a-b) < .01 for a,b in zip(pixel(game, *point), (.1,.15,.2))), 'tap is after overwrite/HUD or float decoding corrupted'
            assert all(abs(a-b) < .10 for a,b in zip(pixel(remix, *point), (v/255 for v in tr.REMIX))), 'wrong published Remix pixels'
    assert matched, 'no stationary-camera candidate pair captured'
    moving_dir = work / 'moving-pairs'; moving_dir.mkdir()
    scenario('moving', {'NIER_REMIX_LIVE_TRUTH_PAIR_DIR': win(moving_dir), 'NIER_REMIX_LIVE_CAMERA_ORBIT': '180'})
    moving = [json.loads(f.read_text()) for f in moving_dir.glob('*.json')]
    assert 1 <= len(moving) <= 4 and any(m['status'] == 'rejected-camera' for m in moving), 'moving-camera mismatch not rejected'
    for m in moving:
        equal = all(abs(a-b) <= 1e-4 for a,b in zip(m['game_camera'],m['remix_camera']))
        assert m['camera_matched'] == equal
        if not equal: assert m['status'] == 'rejected-camera' and not m.get('game_file') and not m.get('remix_file')
    bad = work / 'not-a-directory'; bad.write_bytes(b'keep this file')
    scenario('write-failure', {'NIER_REMIX_LIVE_TRUTH_PAIR_DIR': win(bad)})
    assert bad.read_bytes() == b'keep this file', 'failed tap overwrote caller data'


def main():
    if sys.argv[1:] == ['--inside']: return check()
    OUT.mkdir(parents=True, exist_ok=True)
    session = Path(tempfile.mkdtemp(prefix='session-', dir=OUT))
    template = OUT / 'template'; template.mkdir(exist_ok=True)
    token = uuid.uuid4().hex
    prefix = prepare_private_prefix(template, session / 'prefix', token)
    for name in ['home', 'cache', 'xdg']:
        (session / name).mkdir()
    (session / 'xdg').chmod(0o700)
    env = os.environ.copy()
    env.update(T1_GATE_SESSION=str(session), WINEPREFIX=str(prefix), NIER_RUN_TOKEN=token,
               STEAM_COMPAT_DATA_PATH=str(prefix), HOME=str(session / 'home'), XDG_CACHE_HOME=str(session / 'cache'),
               XDG_RUNTIME_DIR=str(session / 'xdg'), WINEDEBUG='-all', WAYLAND_DISPLAY='', LIBGL_ALWAYS_SOFTWARE='1',
               GALLIUM_DRIVER='llvmpipe', WINEDLLOVERRIDES='d3d11=n,b;winemenubuilder.exe=d;mscoree,mshtml=')
    try:
        subprocess.run(['xvfb-run', '-a', '-s', '-screen 0 1920x1080x24', sys.executable,
                        str(Path(__file__).resolve()), '--inside'], env=env, check=True, cwd=C)
    finally:
        cleanup(token, prefix)


if __name__ == '__main__':
    try:
        main(); print(json.dumps({'passed': True}))
    except (Exception, SystemExit) as exc:
        print(json.dumps({'passed': False, 'error': str(exc)[:1800]})); sys.exit(1)
